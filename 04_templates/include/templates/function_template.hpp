#include <print>
#include <string>
#include <type_traits>

// ═══════════════════════════════════════════════════════════════════════════════
// Part 1: 函数模板基础 — 用类型参数化函数
// ═══════════════════════════════════════════════════════════════════════════════
// 【是什么】函数模板是一张"蓝图"——编译器根据它，为不同的类型生成对应版本的函数。
// 【为什么】没有模板时，你需要为 int、double、string 各写一份 max()，代码完全重复。
// 【什么时候用】当你发现多个函数的逻辑一模一样，只是参数类型不同时，就可以用模板。

// 定义一个函数模板：T 是"模板参数"，代表"某种类型"
template <typename T>
T my_max(T a, T b) {
    return (a > b) ? a : b;
}

// C++ 也允许用 class 代替 typename，效果完全相同
template <class T>
T my_min(T a, T b) {
    return (a < b) ? a : b;
}

// ═══════════════════════════════════════════════════════════════════════════════
// Part 2: 隐式实例化 vs 显式实例化
// ═══════════════════════════════════════════════════════════════════════════════
// 【隐式实例化】编译器根据实参类型自动推导 T，然后生成对应函数
//   - my_max(3, 5)      → 编译器推导 T = int，生成 my_max<int>(int, int)
//   - my_max(3.14, 2.71) → 编译器推导 T = double
// 【显式实例化】你手动指定 T，编译器强制使用你指定的类型
//   - my_max<double>(3, 5)  → T = double，int 3 和 5 被隐式转换为 double

// ═══════════════════════════════════════════════════════════════════════════════
// Part 3: 类型推导规则深入
// ═══════════════════════════════════════════════════════════════════════════════
// 模板实参推导有几个重要规则：
//
// 1. 引用折叠：T& + & → T&, T&& + & → T&, T& + && → T&, T&& + && → T&&
// 2. 转发引用（万能引用）：T&& 配合 auto 推导时，既能绑定左值也能绑定右值
//    - my_forward(42)       → T = int,  参数类型 = int&&
//    - my_forward(x)        → T = int&, 参数类型 = int& (引用折叠!)
// 3. 推导时不会做隐式转换（除了几个例外：数组退化为指针、函数退化为函数指针等）
//    - my_max(3, 5.0)  ← 编译错误！T 同时推导为 int 和 double，冲突

template <typename T>
void print_type_info(T&& val) {
    // std::is_same_v 和 std::is_lvalue_reference_v 来自 <type_traits>
    if constexpr (std::is_lvalue_reference_v<T>) {
        std::println("  T 是左值引用，参数是左值引用(折叠后)");
    } else {
        std::println("  T 不是引用，参数是右值引用");
    }
}

// ═══════════════════════════════════════════════════════════════════════════════
// Part 4: C++20 auto 模板参数 — 更简洁的写法
// ═══════════════════════════════════════════════════════════════════════════════
// C++20 允许用 auto 声明模板参数，等价于传统的 template<typename T> 写法
// 优势：语法更简洁，阅读体验更好
// 限制：不能用 auto 做 SFINAE 或者偏特化（高级用法仍需传统写法）

// C++20 写法 — 每个参数类型独立
auto auto_max(auto a, auto b) {   // a 和 b 可以是不同类型
    return (a > b) ? a : b;
}

// 如果需要 a 和 b 类型相同，用 concept（见 07_concepts）或显式约束
