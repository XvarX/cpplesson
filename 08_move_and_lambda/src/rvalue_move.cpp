#include "move_lambda/rvalue_move.hpp"

namespace move_lambda {

// ═══════════════════════════════════════════════════════════════════════════════
// create_good — ✅ 好写法: 返回局部变量, 编译器会自动做 NRVO
// ═══════════════════════════════════════════════════════════════════════════════
// NRVO(具名返回值优化): 编译器直接在调用方的内存位置构造返回值, 跳过拷贝/移动
Tracker create_good() {
    Tracker t(42);
    return t;  // NRVO: 直接在调用方构造, 没有拷贝/移动
}

// ═══════════════════════════════════════════════════════════════════════════════
// create_bad — ❌ 坏写法: 对局部变量 std::move, 反而阻止了 NRVO!
// ═══════════════════════════════════════════════════════════════════════════════
Tracker create_bad() {
    Tracker t(99);
    return std::move(t);  // 阻止了 NRVO, 强制移动!
}

} // namespace move_lambda
