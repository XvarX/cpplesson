#include "fundamentals/pointers_refs.hpp"

namespace fundamentals {

// ═══════════════════════════════════════════════════════════════════════════════
// 基础数学运算 — 用于函数指针演示
// 这些函数故意保持简单，重点是演示函数指针的用法而非数学逻辑
// ═══════════════════════════════════════════════════════════════════════════════

int add(int a, int b) { return a + b; }
int sub(int a, int b) { return a - b; }
int mul(int a, int b) { return a * b; }

// ═══════════════════════════════════════════════════════════════════════════════
// calc — 通过函数指针回调，经典的"策略模式"实现
// ═══════════════════════════════════════════════════════════════════════════════
// 参数 op 的类型是 int (*)(int, int)，即"指向接受两个 int 返回 int 的函数的指针"。
// 调用者可以传入 add / sub / mul 或任何匹配签名的函数/lambda。
// 注意: 无捕获的 lambda 可以隐式转换为函数指针。
int calc(int x, int y, int (*op)(int, int)) {
    return op(x, y);   // 通过指针调用函数
}

// ── 使用类型别名的版本 ──
int calc_v2(int x, int y, BinaryIntOp op) {
    return op(x, y);
}

} // namespace fundamentals
