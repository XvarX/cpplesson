#include "fundamentals/const_static.hpp"

namespace fundamentals {

// ═══════════════════════════════════════════════════════════════════════════════
// create_counter — static 局部变量演示
// ═══════════════════════════════════════════════════════════════════════════════
// static 局部变量的特点:
//   - 生命周期 = 程序运行全程 (存储在静态数据区，而非栈)
//   - 作用域仅限本函数内 (封装性好)
//   - 首次执行到这一行时初始化，之后跳过
//   - C++11 起保证初始化是线程安全的 (编译器插入隐式锁)
// 适用场景: 缓存/记忆化、单例模式、调用计数
int create_counter() {
    static int count = 0;
    return ++count;
}

// ═══════════════════════════════════════════════════════════════════════════════
// get_counter_value — 获取当前计数值 (不递增)
// ═══════════════════════════════════════════════════════════════════════════════
int get_counter_value() {
    // 注意: 这里无法直接访问 create_counter 中的 static 变量，
    // 因为那是 create_counter 函数作用域内的局部变量。
    // 这是一种设计权衡: 封装性 vs 可观测性。
    // 如果需要外部访问，应该把 static 变量提升到类或命名空间作用域。
    // 这里返回 -1 表示"不可直接访问"，实际场景中你可能:
    //   - 把计数器改为 static 成员变量
    //   - 使用 std::atomic<int> 配合全局可见性
    return -1;
}

} // namespace fundamentals
