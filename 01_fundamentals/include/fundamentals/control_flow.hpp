#include <string>
#include <string_view>

namespace fundamentals {

// ═══════════════════════════════════════════════════════════════════════════════
// classify_number — 演示 return 在不同控制流中的使用
// ═══════════════════════════════════════════════════════════════════════════════
// 利用 early return 避免深层嵌套，是 C++ 中推崇的风格。
// 注意 [[nodiscard]]: 调用者不应该忽略这个纯计算函数的返回值。
[[nodiscard]] std::string classify_number(int n);

// ═══════════════════════════════════════════════════════════════════════════════
// day_name — 演示 switch 基本用法
// ═══════════════════════════════════════════════════════════════════════════════
// switch 的关键规则:
//   - case 值必须是编译期常量 (整数/枚举)
//   - 每个 case 要以 break 结束，否则会"穿透"到下一个 case
//   - 编译器可为 switch 生成跳转表 (O(1) vs if-else 链的 O(n))
[[nodiscard]] std::string_view day_name(int day);

// ═══════════════════════════════════════════════════════════════════════════════
// describe_type — 演示 [[fallthrough]] (C++17)
// ═══════════════════════════════════════════════════════════════════════════════
// [[fallthrough]]: 属性标记，告诉编译器和读者"此处没有 break 是有意的"。
// 消除编译器警告，同时向读者传达意图。
// 注意: [[fallthrough]] 必须放在它要穿透到的 case 之前。
void describe_type(char c);

// ═══════════════════════════════════════════════════════════════════════════════
// 关键概念速查
// ═══════════════════════════════════════════════════════════════════════════════
// if/else:        基本条件分支，支持初始化语句 if (init; cond) (C++17)
// switch:         基于整数的多路分支，编译器可优化为跳转表
// [[fallthrough]]:显式标记有意穿透 (C++17)，消除警告
// for:            三种形式 — 传统 for、range-for (C++11)、带初始化的 range-for (C++20)
// while:          先判断再执行 (可能一次都不执行)
// do-while:       先执行再判断 (至少执行一次)，末尾分号必须有!
// break:          立即退出当前循环或 switch (只退出一层!)
// continue:       跳过本次循环剩余部分，进入下一次迭代
// goto:           无条件跳转，几乎被现代 C++ 抛弃，唯一合理场景是跳出深层嵌套

} // namespace fundamentals
