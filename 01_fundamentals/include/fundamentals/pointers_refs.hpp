namespace fundamentals {

// ═══════════════════════════════════════════════════════════════════════════════
// 基础数学运算 (用于函数指针演示)
// ═══════════════════════════════════════════════════════════════════════════════
int add(int a, int b);
int sub(int a, int b);
int mul(int a, int b);

// ═══════════════════════════════════════════════════════════════════════════════
// 使用函数指针作为回调 — 经典的"策略模式"实现
// ═══════════════════════════════════════════════════════════════════════════════
// calc 接受两个 int 和一个函数指针，返回运算结果。
// 函数指针类型: int (*op)(int, int)
//   - 返回类型: int
//   - 参数: (int, int)
// 现代替代: std::function 更灵活，支持 lambda；但函数指针是理解底层的基础。
int calc(int x, int y, int (*op)(int, int));

// ═══════════════════════════════════════════════════════════════════════════════
// 函数指针类型别名 — 简化复杂声明
// ═══════════════════════════════════════════════════════════════════════════════
// 使用 using 比直接写 int (*)(int, int) 更清晰
using BinaryIntOp = int (*)(int, int);

// 使用类型别名的 calc 重载
int calc_v2(int x, int y, BinaryIntOp op);

// ═══════════════════════════════════════════════════════════════════════════════
// 关键概念速查
// ═══════════════════════════════════════════════════════════════════════════════
// 指针 (T*):     存储地址的变量，可以为空，可重新指向，需要 * 解引用
// 引用 (T&):     已存在变量的别名，不能为空，终身绑定，直接用
// nullptr:       空指针字面量 (C++11)，类型 std::nullptr_t，永不与整数混淆
// 函数指针:      指向函数入口地址，语法: 返回类型 (*指针名)(参数列表)
// void*:         无类型指针，可存放任意地址，不能解引用，使用时需转型
// const T*:      指向 const T 的指针 (不能通过指针修改)
// T* const:      const 指针 (不能重新指向)
// const T&:      const 引用 (不能通过引用修改)，可绑定到临时对象延长其生命周期

} // namespace fundamentals
