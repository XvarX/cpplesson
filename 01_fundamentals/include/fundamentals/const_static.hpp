#include <string_view>

namespace fundamentals {

// ═══════════════════════════════════════════════════════════════════════════════
// constexpr 函数: 如果参数是编译期常量，返回值也是编译期常量
// ═══════════════════════════════════════════════════════════════════════════════
// constexpr 函数在 C++11 中限制很多（只能有一条 return 语句），
// C++14/17/20 逐步放宽，现在支持循环、分支、甚至 try-catch (C++20)。
constexpr int square(int x) { return x * x; }

// ═══════════════════════════════════════════════════════════════════════════════
// consteval (C++20): 强制必须在编译期求值
// ═══════════════════════════════════════════════════════════════════════════════
// 与 constexpr 的区别: consteval 函数绝不生成运行时代码，
// 如果参数不是编译期常量则直接编译错误。
consteval int compile_square(int x) { return x * x; }

// ═══════════════════════════════════════════════════════════════════════════════
// static 局部变量演示: 生命周期 = 程序运行全程，作用域仅限函数内
// ═══════════════════════════════════════════════════════════════════════════════
// 每次调用返回递增的计数器值。
// 首次执行到这一行时初始化，之后跳过，保留上一次的值。
// C++11 起保证 static 局部变量初始化是线程安全的。
int create_counter();

// ═══════════════════════════════════════════════════════════════════════════════
// inline 变量 (C++17): 可以在头文件中定义且不违反 ODR
// ═══════════════════════════════════════════════════════════════════════════════
// 每个包含此头文件的 .cpp 共享同一个实例。
// 替代了传统的 extern 声明 + 单独 .cpp 定义的繁琐模式。
inline int inline_counter = 0;

// ═══════════════════════════════════════════════════════════════════════════════
// 辅助: 获取 static 局部变量计数器的当前值（不递增）
// ═══════════════════════════════════════════════════════════════════════════════
int get_counter_value();

} // namespace fundamentals
