#include <string_view>

namespace fundamentals {

// ═══════════════════════════════════════════════════════════════════════════════
// 函数重载演示: 同名函数，不同参数类型
// ═══════════════════════════════════════════════════════════════════════════════
// 重载规则:
//   1) 参数数量不同 → 重载
//   2) 参数类型不同 → 重载
//   3) 仅返回值类型不同 → ❌ 不是重载! 编译错误!
//   4) const 成员函数 vs 非 const → 重载 (对成员函数)
void print_info(int value);
void print_info(double value);
void print_info(std::string_view msg);

// ═══════════════════════════════════════════════════════════════════════════════
// 尾置返回类型 (trailing return type) 的模板函数
// ═══════════════════════════════════════════════════════════════════════════════
// 语法: auto 函数名(参数) -> 实际返回类型
// 适用于返回类型依赖于参数的泛型函数，或统一函数签名的书写风格
template<typename T, typename U>
auto multiply(T a, U b) -> decltype(a * b) {
    return a * b;
}

// ═══════════════════════════════════════════════════════════════════════════════
// [[nodiscard]]: 忽略返回值会产生编译器警告 (C++17)
// ═══════════════════════════════════════════════════════════════════════════════
// 用于"调用者必须使用返回值"的场景，防止遗漏错误检查。
// 常见应用: 返回错误码的函数、纯计算函数（忽略返回值意味着无意义的调用）。
[[nodiscard]] int compute_important_value();
[[nodiscard]] bool validate_input(int x);

// ═══════════════════════════════════════════════════════════════════════════════
// inline 函数: 建议编译器在调用处展开，避免函数调用开销
// ═══════════════════════════════════════════════════════════════════════════════
// 注意: inline 只是建议，编译器可能忽略。
// 现代 inline 的主要作用: 允许函数定义出现在头文件中，
// 多个翻译单元包含也不会产生重复定义错误 (ODR 豁免)。
inline int fast_max(int a, int b) { return (a > b) ? a : b; }

// ═══════════════════════════════════════════════════════════════════════════════
// constexpr 函数: 编译期也可执行的函数
// ═══════════════════════════════════════════════════════════════════════════════
// 如果所有参数都是编译期常量，函数在编译期求值；
// 如果有运行期参数，则在运行期求值（与普通函数一样）。
constexpr int factorial(int n) {
    return (n <= 1) ? 1 : n * factorial(n - 1);
}

// ═══════════════════════════════════════════════════════════════════════════════
// 关键概念速查
// ═══════════════════════════════════════════════════════════════════════════════
// 声明 (declaration): 告诉编译器函数签名，通常在头文件中
// 定义 (definition):   提供函数体 { ... }，通常在 .cpp 文件中
// 重载 (overloading): 同一作用域内同名函数，参数列表必须不同
// 默认参数:           调用者可省略的参数，必须从右往左连续
// inline:             消除小函数调用开销，允许头文件中定义
// [[nodiscard]]:      标记返回值不应被丢弃 (C++17)
// 尾置返回类型:       auto f(args) -> ReturnType，泛型编程利器

} // namespace fundamentals
