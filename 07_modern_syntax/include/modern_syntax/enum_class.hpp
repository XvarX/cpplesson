#pragma once
// ╔══════════════════════════════════════════════════════════════════════════════╗
// ║  modern_syntax/enum_class.hpp                                               ║
// ║  enum class (限定作用域枚举) / 底层类型 / using enum —— 可复用枚举定义     ║
// ╚══════════════════════════════════════════════════════════════════════════════╝

#include <cstdint>
#include <type_traits>

namespace modern_syntax {

// ╔══════════════════════════════════════════════════════════════════════════════╗
// ║  HTTP 状态码枚举 —— 演示指定底层类型控制内存                                ║
// ║  sizeof(HttpStatus) == sizeof(uint16_t) == 2 字节                          ║
// ╚══════════════════════════════════════════════════════════════════════════════╝
enum class HttpStatus : uint16_t {
    OK       = 200,
    NotFound = 404,
    Internal = 500
};

// ╔══════════════════════════════════════════════════════════════════════════════╗
// ║  优先级枚举 —— 演示 uint8_t 底层类型                                        ║
// ╚══════════════════════════════════════════════════════════════════════════════╝
enum class Priority : uint8_t {
    Low    = 0,
    Medium = 128,
    High   = 255
};

// ╔══════════════════════════════════════════════════════════════════════════════╗
// ║  位掩码标志 (flags) 模式 —— 经典的权限位掩码                                ║
// ║  C++ 需要重载按位运算符 (enum class 不隐式转为整数)                          ║
// ╚══════════════════════════════════════════════════════════════════════════════╝
enum class Permission : uint8_t {
    None    = 0,
    Read    = 1 << 0,  // 1
    Write   = 1 << 1,  // 2
    Execute = 1 << 2,  // 4
    All     = Read | Write | Execute
};

// ╔══════════════════════════════════════════════════════════════════════════════╗
// ║  季节枚举 —— 演示 using enum (C++20) 引入枚举值到当前作用域               ║
// ╚══════════════════════════════════════════════════════════════════════════════╝
enum class Season {
    Spring,
    Summer,
    Autumn,
    Winter
};

// ╔══════════════════════════════════════════════════════════════════════════════╗
// ║  泛型枚举转整数函数 —— if constexpr + is_enum                               ║
// ║  传入枚举则转底层数, 否则原样返回                                           ║
// ╚══════════════════════════════════════════════════════════════════════════════╝
template<typename T>
auto to_number(T val) {
    if constexpr (std::is_enum_v<T>) {
        return static_cast<std::underlying_type_t<T>>(val);
    } else {
        return val;
    }
}

// ╔══════════════════════════════════════════════════════════════════════════════╗
// ║  HTTP 方法枚举 —— 练习用                                                    ║
// ╚══════════════════════════════════════════════════════════════════════════════╝
enum class HttpMethod : uint8_t {
    GET,
    POST,
    PUT,
    DELETE
};

} // namespace modern_syntax
