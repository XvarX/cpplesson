#include <initializer_list>
#include <print>
#include <string>

namespace modern_syntax {

// ╔══════════════════════════════════════════════════════════════════════════════╗
// ║  Vec3 —— 自定义数学向量类，演示 initializer_list 的使用                     ║
// ║  接受 {} 初始化: Vec3 v{1.0, 2.0, 3.0};                                    ║
// ╚══════════════════════════════════════════════════════════════════════════════╝
class Vec3 {
public:
    double x{}, y{}, z{};

    // 默认构造
    Vec3() = default;

    // 接受 initializer_list 的构造函数
    Vec3(std::initializer_list<double> il) {
        auto it = il.begin();
        if (it != il.end()) x = *it++;
        if (it != il.end()) y = *it++;
        if (it != il.end()) z = *it++;
    }

    void print() const {
        std::println("Vec3({:.1f}, {:.1f}, {:.1f})", x, y, z);
    }
};

// ╔══════════════════════════════════════════════════════════════════════════════╗
// ║  Point —— 聚合类型: 无用户定义构造函数, 无私有的非静态成员, 无虚函数等     ║
// ║  支持聚合初始化: Point p{3.0, 4.0, "原点"};                                ║
// ║  支持 C++20 指定初始化: Point p{.x=10.0, .y=20.0, .label="终点"};          ║
// ╚══════════════════════════════════════════════════════════════════════════════╝
struct Point {
    double x;
    double y;
    std::string label;
};

// ╔══════════════════════════════════════════════════════════════════════════════╗
// ║  Config —— 聚合类型带默认值，演示指定初始化的部分初始化                      ║
// ║  Config cfg{.port = 9090, .timeout = 60.0};                                 ║
// ║  其余成员使用默认值: threads=4, use_ssl=true                                ║
// ╚══════════════════════════════════════════════════════════════════════════════╝
struct Config {
    int    port     = 8080;
    int    threads  = 4;
    bool   use_ssl  = true;
    double timeout  = 30.0;
};

// ╔══════════════════════════════════════════════════════════════════════════════╗
// ║  Timer —— 最简单的聚合类型，演示 "最令人烦恼的解析" 问题                    ║
// ╚══════════════════════════════════════════════════════════════════════════════╝
struct Timer {
    int seconds;
};

} // namespace modern_syntax
