// ═══════════════════════════════════════════════════════════════════════════════
// Person — 构造函数基础 (默认/带参)
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: 构造函数在对象创建时自动调用，负责初始化成员
// 为什么: 保证对象创建后处于有效状态，避免未初始化的成员
// 何时用: 每个类都应定义构造函数，明确初始化策略

class Person {
public:
    // 默认构造 — 无参数
    Person() : name_("未知"), age_(0) {}

    // 带参构造 — 使用初始化列表 (高效: 直接初始化，而非先默认再赋值)
    Person(std::string name, int age)
        : name_(std::move(name)), age_(age) {}

    void introduce() const {
        std::println("我叫{}，今年{}岁", name_, age_);
    }

private:
    std::string name_;
    int age_;
};

// ═══════════════════════════════════════════════════════════════════════════════
// Config — 初始化列表
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: 构造函数冒号后的成员初始化语法 `: member(value), ...`
// 为什么: ① 比在函数体内赋值更高效 (直接构造而非默认构造+赋值)
//         ② const/引用成员只能通过初始化列表初始化
//         ③ 基类构造也只能通过初始化列表调用
// 何时用: 始终优先使用初始化列表，而非函数体内赋值

class Config {
public:
    Config(std::string path, int port)
        : path_(std::move(path))   // 直接移动构造
        , port_(port)              // 直接初始化
         // 正确顺序: path_ 先于 port_ (按声明顺序，非初始化列表顺序!)
    {}

    void show() const {
        std::println("配置路径: {}, 端口: {}", path_, port_);
    }

private:
    std::string path_;
    int port_;
};

// ═══════════════════════════════════════════════════════════════════════════════
// Rectangle — 委托构造: 一个构造调用另一个
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: 构造函数在初始化列表中调用同类另一个构造函数
// 为什么: 避免多个构造函数间代码重复
// 何时用: 多个构造函数需要共享初始化逻辑时

class Rectangle {
public:
    Rectangle(double side)                     // 正方形构造
        : Rectangle(side, side) {}             // 委托给双参数构造

    Rectangle(double w, double h)
        : width_(w), height_(h) {}

    double area() const { return width_ * height_; }

private:
    double width_, height_;
};

// ═══════════════════════════════════════════════════════════════════════════════
// NonCopyable — =delete 禁止拷贝, =default 恢复编译器生成
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: =default 让编译器生成默认版本, =delete 禁止使用
// 为什么: 显式声明意图，提高代码可读性和安全性
// 何时用: =delete 禁止拷贝/移动; =default 恢复编译器生成版本

class NonCopyable {
public:
    NonCopyable() = default;                       // 默认构造
    NonCopyable(const NonCopyable&) = delete;      // 禁止拷贝
    NonCopyable& operator=(const NonCopyable&) = delete;

    NonCopyable(NonCopyable&&) = default;          // 允许移动
    NonCopyable& operator=(NonCopyable&&) = default;
};

// ═══════════════════════════════════════════════════════════════════════════════
// Trivial — =default 显式要求编译器生成
// ═══════════════════════════════════════════════════════════════════════════════

class Trivial {
public:
    Trivial() = default;  // 显式要求编译器生成
    int x = 0;
    // 编译器自动生成拷贝/移动/析构
};

// ═══════════════════════════════════════════════════════════════════════════════
// Duration — explicit 阻止隐式转换
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: explicit 禁止构造函数用于隐式类型转换
// 为什么: 防止意外的隐式转换导致的 bug
// 何时用: 几乎所有单参数构造函数都应加 explicit

class Duration {
public:
    explicit Duration(int seconds)                  // explicit 阻止隐式转换
        : seconds_(seconds) {}

    int total_seconds() const { return seconds_; }

private:
    int seconds_;
};

// ═══════════════════════════════════════════════════════════════════════════════
// Logger — 析构函数演示
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: 对象生命周期结束时自动调用，负责释放资源
// 为什么: RAII 的"释放"环节，确保资源不泄漏
// 何时用: 类持有需要手动释放的资源 (内存/文件/锁/网络连接)

class Logger {
public:
    explicit Logger(std::string name) : name_(std::move(name)) {
        std::println("🔵 [{}] 构造 — 打开日志文件", name_);
    }

    ~Logger() {
        std::println("🔴 [{}] 析构 — 关闭日志文件", name_);
        // 实际场景: 在这里 flush 缓冲区、关闭文件句柄
    }

    std::string_view name() const { return name_; }

private:
    std::string name_;
};

