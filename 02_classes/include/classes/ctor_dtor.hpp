// ⚠️ 常见陷阱
// ═══════════════════════════════════════════════════════════════════════════════
// 1. 初始化列表顺序 = 成员声明顺序，非列表书写顺序 (不同可能导致未定义行为)
// 2. 单参数构造不加 explicit → 意外的隐式转换
// 3. 忘记初始化引用或 const 成员 → 编译错误
// 4. 在析构函数中抛出异常 → 可能导致 std::terminate
// 5. 拷贝构造忘记 const 引用 → 无限递归 (形参会触发拷贝构造)

