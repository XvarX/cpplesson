// ═══════════════════════════════════════════════════════════════════════════════
// Part 1: 三五零法则 — 拷贝控制的黄金法则
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: 三五零法则是决定何时需要定义特殊成员函数的规则
//   零法则: 若类不管理资源，不定义任何特殊函数 — 交给编译器
//   三法则: 若需要自定义析构/拷贝构造/拷贝赋值之一 → 三者都需要
//   五法则: C++11 起，加上移动构造/移动赋值 → 五者都需要
// 为什么: 编译器自动生成可能错误 (浅拷贝导致 double-free)
// 何时用: 根据是否管理资源选择零或五

void part1_rule_of_five() {
    print_subtitle("Part 1: 三五零法则");

    Buffer buf1(5);                       // 构造
    Buffer buf2 = buf1;                   // 拷贝构造
    std::println("buf1 大小: {}, buf2 大小: {} (深拷贝)", buf1.size(), buf2.size());

    Buffer buf3 = std::move(buf1);       // 移动构造
    std::println("移动后 buf1 大小: {} (资源被移走)", buf1.size()); // 期望: 0
}

// ═══════════════════════════════════════════════════════════════════════════════
// Part 2: swap 惯用法 — 实现安全赋值的关键
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: copy-and-swap: 先拷贝一份临时对象，再与自身 swap
// 为什么: ① 异常安全 (拷贝失败时原对象不变)
//         ② 代码复用 (拷贝赋值和移动赋值统一逻辑)
//         ③ 自动处理自赋值
// 何时用: 实现拷贝赋值和移动赋值时

void part2_swap_idiom() {
    print_subtitle("Part 2: swap 惯用法");

    String s1("Hello");
    String s2("World");
    std::println("交换前: s1={}, s2={}", s1.c_str(), s2.c_str());

    s1.swap(s2);  // 成员 swap
    std::println("交换后: s1={}, s2={}", s1.c_str(), s2.c_str());

    String s3("Copy");
    s3 = s1;      // 拷贝赋值 (copy-and-swap)
    std::println("赋值后: s3={}", s3.c_str());
}

// ═══════════════════════════════════════════════════════════════════════════════
// Part 3: noexcept 与移动 — 影响容器行为
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: noexcept 标记函数不抛异常
// 为什么: ① 编译器可生成更优代码
//         ② vector 扩容时: 移动操作标记 noexcept 才用移动，否则降级为拷贝
// 何时用: 移动构造/移动赋值必须 noexcept；析构函数默认 noexcept

void part3_noexcept_move() {
    print_subtitle("Part 3: noexcept 移动");

    std::vector<NoexceptDemo> vec;
    std::println("向 vector 添加元素，观察移动行为:");
    vec.emplace_back(1);
    vec.emplace_back(2);
    std::println("扩容时触发移动 (因为有 noexcept):");
    vec.emplace_back(3); // 触发扩容 → 移动而非拷贝
    std::println("noexcept 移动使 vector 扩容更高效!");
}

