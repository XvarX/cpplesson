// ═══════════════════════════════════════════════════════════════════════════════
// Part 1: 构造函数基础 — 对象的诞生
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: 构造函数在对象创建时自动调用，负责初始化成员
// 为什么: 保证对象创建后处于有效状态，避免未初始化的成员
// 何时用: 每个类都应定义构造函数，明确初始化策略

void part1_constructor_basics() {
    print_subtitle("Part 1: 构造函数基础");

    Person p1;                    // 调用默认构造
    p1.introduce();

    Person p2("艾克斯", 25);     // 调用带参构造
    p2.introduce();
}

// ═══════════════════════════════════════════════════════════════════════════════
// Part 2: 初始化列表 — 成员初始化的正确方式
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: 构造函数冒号后的成员初始化语法 `: member(value), ...`
// 为什么: ① 比在函数体内赋值更高效 (直接构造而非默认构造+赋值)
//         ② const/引用成员只能通过初始化列表初始化
//         ③ 基类构造也只能通过初始化列表调用
// 何时用: 始终优先使用初始化列表，而非函数体内赋值

void part2_init_list() {
    print_subtitle("Part 2: 初始化列表");

    Config cfg("/etc/app.conf", 8080);
    cfg.show();
}

// ═══════════════════════════════════════════════════════════════════════════════
// Part 3: 委托构造 — 一个构造调用另一个
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: 构造函数在初始化列表中调用同类另一个构造函数
// 为什么: 避免多个构造函数间代码重复
// 何时用: 多个构造函数需要共享初始化逻辑时

void part3_delegating_ctor() {
    print_subtitle("Part 3: 委托构造");

    Rectangle square(5.0);        // 委托 → Rectangle(5.0, 5.0)
    Rectangle rect(6.0, 4.0);
    std::println("正方形面积: {:.0f}", square.area());  // 期望: 25
    std::println("矩形面积:   {:.0f}", rect.area());    // 期望: 24
}

// ═══════════════════════════════════════════════════════════════════════════════
// Part 4: =default / =delete — 明确控制特殊函数
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: =default 让编译器生成默认版本, =delete 禁止使用
// 为什么: 显式声明意图，提高代码可读性和安全性
// 何时用: =delete 禁止拷贝/移动; =default 恢复编译器生成版本

void part4_default_delete() {
    print_subtitle("Part 4: =default / =delete");

    NonCopyable a;
    // NonCopyable b = a;         // ❌ 拷贝构造被 delete
    NonCopyable c = std::move(a); // ✅ 移动构造可用

    Trivial t1;
    Trivial t2 = t1;             // ✅ 默认生成的拷贝构造
    std::println("t2.x = {}", t2.x);
}

// ═══════════════════════════════════════════════════════════════════════════════
// Part 5: explicit — 阻止隐式转换
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: explicit 禁止构造函数用于隐式类型转换
// 为什么: 防止意外的隐式转换导致的 bug
// 何时用: 几乎所有单参数构造函数都应加 explicit

void process(Duration d) {
    std::println("处理时长: {} 秒", d.total_seconds());
}

void part5_explicit() {
    print_subtitle("Part 5: explicit");

    process(Duration(10));  // ✅ 显式创建
    // process(10);         // ❌ 编译错误: explicit 阻止了隐式转换
    // 如果没有 explicit, process(10) 将静默把 int 转为 Duration — 很危险!
    std::println("explicit 让意图更清晰，编译器会阻止意外的隐式转换");
}

// ═══════════════════════════════════════════════════════════════════════════════
// Part 6: 析构函数 — 对象的消亡
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: 对象生命周期结束时自动调用，负责释放资源
// 为什么: RAII 的"释放"环节，确保资源不泄漏
// 何时用: 类持有需要手动释放的资源 (内存/文件/锁/网络连接)

void part6_destructor() {
    print_subtitle("Part 6: 析构函数");

    std::println("进入作用域");
    {
        Logger log("session_1");
        // 使用 log 进行日志记录 ...
    } // ← log 在此析构, 自动释放资源
    std::println("离开作用域 (Logger 已自动析构)");
}

// ═══════════════════════════════════════════════════════════════════════════════
// ⚠️ 常见陷阱
// ═══════════════════════════════════════════════════════════════════════════════
// 1. 初始化列表顺序 = 成员声明顺序，非列表书写顺序 (不同可能导致未定义行为)
// 2. 单参数构造不加 explicit → 意外的隐式转换
// 3. 忘记初始化引用或 const 成员 → 编译错误
// 4. 在析构函数中抛出异常 → 可能导致 std::terminate
// 5. 拷贝构造忘记 const 引用 → 无限递归 (形参会触发拷贝构造)

// ═══════════════════════════════════════════════════════════════════════════════
// ✏️ 练习
// ═══════════════════════════════════════════════════════════════════════════════
// 1. 定义 Vector3D 类，使用初始化列表初始化 x/y/z
// 2. 为 Vector3D 添加委托构造: 单参数构造委托给三参数构造 (x=y=z)
// 3. 定义 DatabaseConnection 类，构造时连接，析构时断开 (打印模拟即可)
// 4. 为一个"只能移动不能拷贝"的 UniquePtr 类使用 =delete 和 =default

int main() {
    print_header("02 构造函数与析构函数");
    part1_constructor_basics();
    part2_init_list();
    part3_delegating_ctor();
    part4_default_delete();
    part5_explicit();
    part6_destructor();
    print_separator();
    std::println("🎉 02_ctor_dtor 完成！");
    return 0;
}
