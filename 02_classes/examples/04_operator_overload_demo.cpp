// ═══════════════════════════════════════════════════════════════════════════════
// Part 1: 算术运算符 — 让自定义类型支持 + - * /
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: 重载 +、-、*、/ 等运算符让自定义类型像内置类型一样运算
// 为什么: 代码可读性: vec3 a = b + c; 比 vec3 a = b.add(c); 更直观
// 何时用: 类型具有自然的算术语义时 (向量、矩阵、复数、货币等)

void part1_arithmetic() {
    print_subtitle("Part 1: 算术运算符");

    Vec2 a(3, 4), b(1, 2);
    auto c = a + b;         // operator+(Vec2, Vec2)
    auto d = c * 2.0;       // operator*(Vec2, double)
    auto e = 3.0 * a;       // operator*(double, Vec2)
    std::print("a + b = "); c.print();     // 期望: (4, 6)
    std::print("c * 2 = "); d.print();     // 期望: (8, 12)
    std::print("3 * a = "); e.print();     // 期望: (9, 12)
}

// ═══════════════════════════════════════════════════════════════════════════════
// Part 2: 三路比较 <=> (C++20) — 一个运算符生成所有比较
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: operator<=> 返回 std::strong_ordering / weak_ordering / partial_ordering
// 为什么: 只需定义 <=> (和 ==)，编译器自动生成 <,<=,>,>=,!=
// 何时用: 类型需要排序/比较时，优先用 <=> 替代手写所有比较运算符

void part2_spaceship() {
    print_subtitle("Part 2: <=> 三路比较 (C++20)");

    Version v1{1, 2, 3}, v2{1, 3, 0}, v3{1, 2, 3};

    // 编译器自动生成了所有 6 个比较运算符!
    if (v1 < v2)   std::println("v1 < v2  ✅");  // 1.2.3 < 1.3.0
    if (v1 != v2)  std::println("v1 != v2 ✅");
    if (v1 == v3)  std::println("v1 == v3 ✅");  // 相同版本
    if (v1 <= v2)  std::println("v1 <= v2 ✅");

    // 也可以手动使用 <=>
    auto result = v1 <=> v2;
    if (result < 0) std::println("手动比较: v1 < v2 (结果为负)");
}

// ═══════════════════════════════════════════════════════════════════════════════
// Part 3: operator[] 和 operator() — 下标与函数调用
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: operator[] 让对象像数组一样访问; operator() 让对象像函数一样调用
// 为什么: operator[]: 容器、矩阵等需要索引访问
//         operator(): 仿函数 (functor)、回调包装、lambda 底层就是它
// 何时用: operator[]: 有索引语义; operator(): 需要可调用对象

void part3_subscript_and_call() {
    print_subtitle("Part 3: operator[] 和 operator()");

    Matrix m;
    m[0] = 3.14;                                   // 非 const operator[]
    std::println("m[0] = {:.2f}", m[0]);

    Multiplier times3(3);
    std::println("times3(7) = {}", times3(7));      // "调用"对象: 期望 21

    // operator() 使得对象可以作为回调传递
    std::vector<int> vals{1, 2, 3};
    // std::transform 接受可调用对象 (lambda 底层也是 operator())
}

// ═══════════════════════════════════════════════════════════════════════════════
// Part 4: 成员 vs 非成员重载 — 选择原则
// ═══════════════════════════════════════════════════════════════════════════════
// 是什么: 运算符可定义为成员函数 (this 作为左操作数) 或非成员函数
// 为什么: 非成员支持左操作数隐式转换 (如 3 * vec)
//         成员函数无法将内置类型作为左操作数
// 何时用:
//   = [] () ->           必须是成员
//   复合赋值 += -= *= /=  首选成员
//   二元算术 + - * /      首选非成员 (复用复合赋值)
//   比较 == != < <= > >=  首选非成员 (对称性)
//   << >> (IO)            必须是非成员 (因为左操作数是 ostream)

void part4_member_vs_nonmember() {
    print_subtitle("Part 4: 成员 vs 非成员重载");

    Score s1(80), s2(90);
    if (s1 < s2) std::println("80 < 90 ✅ (成员 operator<)");
    if (s1 == Score(80)) std::println("80 == 80 ✅ (非成员 operator==)");
    // if (100 == s1) ...  非成员 == 允许左操作数隐式转换
}

