#pragma once

// ── 对象式宏: 无参数的文本替换 ────────────────────────────────────────────────
#define PI 3.14159265358979323846
#define APP_NAME "CppLesson"

// ── 函数式宏: 参数必须整体加括号, 防止优先级错误 ─────────────────────────────
// SQUARE(2+3) → ((2+3) * (2+3)) = 25 (若不加括号: 2+3*2+3 = 11!)
#define SQUARE(x) ((x) * (x))

#define MAX(a, b) ((a) > (b) ? (a) : (b))

// ── 字符串化 (#): 把宏参数变成字符串字面量 ────────────────────────────────────
// 两级展开是标准惯用法: 先让 x 完成宏替换, 再字符串化
#define STRINGIFY_IMPL(x) #x
#define STRINGIFY(x) STRINGIFY_IMPL(x)

// ── 标记拼接 (##): 把两个 token 粘成一个新的标识符 ───────────────────────────
#define CONCAT_IMPL(a, b) a##b
#define CONCAT(a, b) CONCAT_IMPL(a, b)

// MAKE_VAR(my_var_, 1) → 展开为 my_var_1 — 用拼接生成变量名
#define MAKE_VAR(prefix, n) CONCAT(prefix, n)
