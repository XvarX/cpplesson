// ── Part 1: std::pair — 键值对基础 ────────────────────────────────────────────
// 是什么: 两个值的简单聚合，通过 .first / .second 访问
// 为什么: map 的元素类型; 函数返回两个相关值的最简单方式
// 什么时候用: map 操作; 需要成对返回 (如 {最小值, 最大值})
void part1_pair();

// ── Part 2: std::tuple — N 个值的聚合 ─────────────────────────────────────────
// 是什么: 固定大小的异构值集合，可包含任意数量、任意类型的值
// 为什么: 需要返回/传递多个不同类型值 (替代输出参数); pair 只能存 2 个
// 什么时候用: 多值返回; 临时聚合数据; 代替"只有一次使用的"结构体
void part2_tuple();

// ── Part 3: std::optional — 可能没有值 ────────────────────────────────────────
// 是什么: 可能包含值也可能不包含的类型 (替代 null/NULL/-1 等魔法值)
// 为什么: 类型安全地表达"无值"，避免空指针和魔法值带来的 bug
// 什么时候用: 查找可能失败; 配置项可能不存在; 函数返回"可能没有结果"
void part3_optional();

// ── Part 4: std::variant — 类型安全的联合体 ───────────────────────────────────
// 是什么: 类型安全的 union，可以持有指定类型列表中的任意一种类型
// 为什么: 比 union 安全 (自动析构、类型检查); 比继承+多态轻量 (无堆分配)
// 什么时候用: 状态机; 错误或成功结果; AST 节点; 替代 tagged union
void part4_variant();

// ── Part 5: std::any — 任意类型的容器 ─────────────────────────────────────────
// 是什么: 类型擦除的容器，可以存储任意可拷贝类型的值
// 为什么: 需要存储"任何类型"但不需要 variant 的显式类型列表
// 什么时候用: 配置值存储、通用容器、插件系统的参数传递 (variant 更优时优先用 variant)
void part5_any();

