// ── Part 1: std::vector — 动态数组，内存连续 ─────────────────────────────────
// 是什么: 连续内存的动态数组，容量(capacity) ≥ 大小(size)
// 为什么: 需要随机访问 O(1) 和尾部增删 O(1) 摊还时首选
// 什么时候用: 大多数场景的默认选择；大量随机访问、尾部插入、缓存友好
void part1_vector();

// ── Part 2: std::deque — 双端队列，分段连续内存 ──────────────────────────────
// 是什么: 双端队列，由多个固定大小的内存块组成，两端 O(1) 插入删除
// 为什么: 需要在头部和尾部高效插入/删除，而 vector 只能在尾部
// 什么时候用: 需要在两端操作；不需要元素地址绝对稳定
void part2_deque();

// ── Part 3: std::list — 双向链表 ─────────────────────────────────────────────
// 是什么: 双向链表，每个节点有前驱和后继指针
// 为什么: 任意位置插入/删除 O(1)（已知位置），迭代器不会因插入/删除而失效
// 什么时候用: 频繁在中间插入/删除；需要 splice/merge 操作；迭代器稳定性要求高
void part3_list();

// ── Part 4: std::forward_list — 单向链表 ─────────────────────────────────────
// 是什么: 单向链表，每个节点只有后继指针，比 list 更省内存
// 为什么: 只需要正向遍历时，forward_list 比 list 节省每个节点的指针开销
// 什么时候用: 内存敏感且只需要正向遍历；不需要 size() 的场景
void part4_forward_list();

// ── Part 5: std::array — 固定大小数组 ────────────────────────────────────────
// 是什么: 编译期固定大小的数组封装，大小是类型的一部分
// 为什么: 比 C 数组安全（有边界检查的 at()）；不退化指针；支持 STL 算法
// 什么时候用: 编译期已知大小且不变；替代 C 风格数组；嵌入式/性能敏感场景
void part5_array();

// ── Part 6: 容器选择指南与复杂度对比 ─────────────────────────────────────────
void part6_choose_container();

// ── 常见陷阱 ─────────────────────────────────────────────────────────────────
void sequential_containers_pitfalls();

// ── 练习 ────────────────────────────────────────────────────────────────────
void sequential_containers_exercises();

