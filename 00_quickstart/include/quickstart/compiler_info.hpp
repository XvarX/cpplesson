// ═══════════════════════════════════════════════════════════════════════════════
// 编译期 C++23 版本静默检查
// 如果编译器不支持 C++23，程序将在此处编译失败
// 这是 inline static_assert 在头文件中的典型用法：
// 任何包含本头文件的翻译单元都必须满足此条件
//
// 注意：MSVC 默认不更新 __cplusplus 宏，需要使用 _MSVC_LANG
//       CMake 会通过 /Zc:__cplusplus 修复此问题，但双保险更安全
// ═══════════════════════════════════════════════════════════════════════════════
#if defined(_MSC_VER)
static_assert(_MSVC_LANG >= 202302L, "编译器不支持 C++23，请升级到 MSVC 2022+！");
#else
static_assert(__cplusplus >= 202302L, "编译器不支持 C++23，请升级到 GCC 14+ / Clang 18+！");
#endif

